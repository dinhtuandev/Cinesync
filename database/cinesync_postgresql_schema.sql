-- CineSync - Database schema for PostgreSQL 16+
-- Based on CineSync_ERD.md. Run this script on a new/empty database.
-- NOTE: There is intentionally NO "movies" table. Movie data (title, poster,
-- genres, episodes/servers) is always sourced live/cached from a third-party
-- Movie Data Provider (MDP). The real provider name/base URL/endpoints are
-- NOT documented anywhere in this repo (public/forkable) — they are
-- configured via environment variables only (see 08_CineSync_Technical_Spec.md
-- section 10). Tables below reference movies only by movie_slug (logical
-- reference, no physical FOREIGN KEY).
-- The schema has 14 tables total: 10 foundational tables (roles, app_users,
-- password_reset_requests, favorites, watchlists, watch_history, ratings,
-- comments, comment_reports, api_call_logs) plus 4 tables for Watch Party
-- and the social layer (watch_party_rooms, watch_party_members,
-- user_follows, recommendations).

BEGIN;

-- =====================================================================
-- PHẦN 1 — Bảng nghiệp vụ nền tảng (tài khoản, tương tác phim, bình luận)
-- =====================================================================

CREATE TABLE roles (
    role_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name VARCHAR(20) NOT NULL UNIQUE,
    description VARCHAR(255),
    CONSTRAINT ck_roles_role_name CHECK (role_name IN ('USER', 'ADMIN'))
);

CREATE TABLE app_users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id SMALLINT NOT NULL REFERENCES roles(role_id),
    full_name VARCHAR(150) NOT NULL,
    email VARCHAR(254) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    avatar_url VARCHAR(500),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    -- Cho phép User ẩn hoạt động của mình khỏi Feed bạn bè (mục 4.6 BA)
    show_activity BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_app_users_full_name CHECK (length(trim(full_name)) > 0),
    CONSTRAINT ck_app_users_email_not_blank CHECK (length(trim(email)) > 0)
);

CREATE UNIQUE INDEX ux_app_users_email_lower ON app_users (lower(email));

CREATE TABLE password_reset_requests (
    reset_request_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(user_id),
    reset_token VARCHAR(255) NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    used_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_password_reset_requests_token CHECK (length(trim(reset_token)) > 0),
    CONSTRAINT ck_password_reset_requests_expiry CHECK (expires_at > created_at)
);

CREATE INDEX ix_password_reset_requests_user_id ON password_reset_requests (user_id);

CREATE TABLE favorites (
    favorite_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(user_id),
    movie_slug VARCHAR(255) NOT NULL,
    movie_name VARCHAR(255) NOT NULL,
    poster_url VARCHAR(500),
    movie_year SMALLINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_favorites_user_movie UNIQUE (user_id, movie_slug),
    CONSTRAINT ck_favorites_movie_slug CHECK (length(trim(movie_slug)) > 0)
);

CREATE INDEX ix_favorites_user_id ON favorites (user_id, created_at DESC);

CREATE TABLE watchlists (
    watchlist_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(user_id),
    movie_slug VARCHAR(255) NOT NULL,
    movie_name VARCHAR(255) NOT NULL,
    poster_url VARCHAR(500),
    movie_year SMALLINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_watchlists_user_movie UNIQUE (user_id, movie_slug),
    CONSTRAINT ck_watchlists_movie_slug CHECK (length(trim(movie_slug)) > 0)
);

CREATE INDEX ix_watchlists_user_id ON watchlists (user_id, created_at DESC);

CREATE TABLE watch_history (
    watch_history_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(user_id),
    movie_slug VARCHAR(255) NOT NULL,
    episode_slug VARCHAR(255) NOT NULL DEFAULT '',
    movie_name VARCHAR(255) NOT NULL,
    poster_url VARCHAR(500),
    progress_seconds INTEGER NOT NULL DEFAULT 0,
    duration_seconds INTEGER,
    last_watched_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_watch_history_user_movie_episode UNIQUE (user_id, movie_slug, episode_slug),
    CONSTRAINT ck_watch_history_movie_slug CHECK (length(trim(movie_slug)) > 0),
    CONSTRAINT ck_watch_history_progress CHECK (progress_seconds >= 0),
    CONSTRAINT ck_watch_history_progress_lte_duration CHECK (
        duration_seconds IS NULL OR progress_seconds <= duration_seconds
    )
);

CREATE INDEX ix_watch_history_user_last_watched ON watch_history (user_id, last_watched_at DESC);

CREATE TABLE ratings (
    rating_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(user_id),
    movie_slug VARCHAR(255) NOT NULL,
    stars SMALLINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_ratings_user_movie UNIQUE (user_id, movie_slug),
    CONSTRAINT ck_ratings_movie_slug CHECK (length(trim(movie_slug)) > 0),
    CONSTRAINT ck_ratings_stars CHECK (stars BETWEEN 1 AND 5)
);

CREATE INDEX ix_ratings_movie_slug ON ratings (movie_slug);

CREATE TABLE comments (
    comment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(user_id),
    parent_comment_id BIGINT REFERENCES comments(comment_id),
    movie_slug VARCHAR(255) NOT NULL,
    episode_slug VARCHAR(255),
    content VARCHAR(2000) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'VISIBLE',
    report_count INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_comments_movie_slug CHECK (length(trim(movie_slug)) > 0),
    CONSTRAINT ck_comments_content CHECK (length(trim(content)) > 0),
    CONSTRAINT ck_comments_status CHECK (status IN ('VISIBLE', 'PENDING_REVIEW', 'HIDDEN')),
    CONSTRAINT ck_comments_not_self_parent CHECK (parent_comment_id IS DISTINCT FROM comment_id),
    CONSTRAINT ck_comments_report_count CHECK (report_count >= 0)
);

CREATE INDEX ix_comments_movie_slug ON comments (movie_slug, created_at DESC);
CREATE INDEX ix_comments_parent_comment_id ON comments (parent_comment_id);
CREATE INDEX ix_comments_status ON comments (status);

CREATE TABLE comment_reports (
    comment_report_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comment_id BIGINT NOT NULL REFERENCES comments(comment_id),
    reporter_user_id BIGINT NOT NULL REFERENCES app_users(user_id),
    reason VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_comment_reports_comment_reporter UNIQUE (comment_id, reporter_user_id)
);

CREATE INDEX ix_comment_reports_comment_id ON comment_reports (comment_id);

-- endpoint should only ever store an INTERNAL route name (e.g. 'movies.home'),
-- never the real MDP domain/path — see 04_CineSync_database_design.md.
CREATE TABLE api_call_logs (
    api_call_log_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    endpoint VARCHAR(255) NOT NULL,
    status_code INTEGER,
    response_time_ms INTEGER,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX ix_api_call_logs_created_at ON api_call_logs (created_at DESC);
CREATE INDEX ix_api_call_logs_endpoint ON api_call_logs (endpoint);

-- Trigger: chỉ hỗ trợ trả lời 1 cấp cho bình luận
CREATE OR REPLACE FUNCTION validate_comment_parent()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_parent_parent_id BIGINT;
    v_parent_movie_slug VARCHAR(255);
BEGIN
    IF NEW.parent_comment_id IS NOT NULL THEN
        SELECT parent_comment_id, movie_slug
          INTO v_parent_parent_id, v_parent_movie_slug
          FROM comments
         WHERE comment_id = NEW.parent_comment_id;

        IF v_parent_movie_slug IS NULL THEN
            RAISE EXCEPTION 'Bình luận cha % không tồn tại', NEW.parent_comment_id;
        END IF;

        IF v_parent_parent_id IS NOT NULL THEN
            RAISE EXCEPTION 'Chỉ hỗ trợ trả lời 1 cấp: không thể trả lời một bình luận đã là trả lời';
        END IF;

        IF v_parent_movie_slug <> NEW.movie_slug THEN
            RAISE EXCEPTION 'Bình luận trả lời phải cùng movie_slug với bình luận gốc';
        END IF;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_comments_validate_parent
BEFORE INSERT OR UPDATE OF parent_comment_id, movie_slug ON comments
FOR EACH ROW
EXECUTE FUNCTION validate_comment_parent();

-- Trigger: đồng bộ report_count và tự chuyển PENDING_REVIEW ở ngưỡng 5
CREATE OR REPLACE FUNCTION apply_comment_report()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_new_count INTEGER;
BEGIN
    UPDATE comments
       SET report_count = report_count + 1,
           updated_at = CURRENT_TIMESTAMP
     WHERE comment_id = NEW.comment_id
     RETURNING report_count INTO v_new_count;

    IF v_new_count >= 5 THEN
        UPDATE comments
           SET status = 'PENDING_REVIEW'
         WHERE comment_id = NEW.comment_id
           AND status = 'VISIBLE';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_comment_reports_apply
AFTER INSERT ON comment_reports
FOR EACH ROW
EXECUTE FUNCTION apply_comment_report();

-- =====================================================================
-- PHẦN 2 — 4 bảng MỚI của CineSync (Watch Party + Xã hội)
-- =====================================================================

-- --- 2.1. Watch Party -------------------------------------------------

CREATE TABLE watch_party_rooms (
    room_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_code VARCHAR(10) NOT NULL,
    host_user_id BIGINT NOT NULL REFERENCES app_users(user_id),
    movie_slug VARCHAR(255) NOT NULL,
    episode_slug VARCHAR(255) NOT NULL DEFAULT '',
    sync_mode VARCHAR(10) NOT NULL,
    status VARCHAR(10) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    closed_at TIMESTAMPTZ,
    CONSTRAINT ck_watch_party_rooms_sync_mode CHECK (sync_mode IN ('AUTO', 'MANUAL')),
    CONSTRAINT ck_watch_party_rooms_status CHECK (status IN ('ACTIVE', 'CLOSED')),
    CONSTRAINT ck_watch_party_rooms_movie_slug CHECK (length(trim(movie_slug)) > 0)
);

-- room_code chỉ cần duy nhất trong số phòng đang ACTIVE (ERD-R-14) —
-- cho phép tái sử dụng mã sau khi phòng đã đóng.
CREATE UNIQUE INDEX ux_watch_party_rooms_active_code
    ON watch_party_rooms (room_code)
    WHERE status = 'ACTIVE';

CREATE INDEX ix_watch_party_rooms_host ON watch_party_rooms (host_user_id);
CREATE INDEX ix_watch_party_rooms_status ON watch_party_rooms (status);

CREATE TABLE watch_party_members (
    watch_party_member_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id BIGINT NOT NULL REFERENCES watch_party_rooms(room_id),
    user_id BIGINT NOT NULL REFERENCES app_users(user_id),
    joined_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    left_at TIMESTAMPTZ
);

CREATE INDEX ix_watch_party_members_room ON watch_party_members (room_id);
CREATE INDEX ix_watch_party_members_user ON watch_party_members (user_id);

-- --- 2.2. Xã hội & Gợi ý cá nhân hóa -----------------------------------

CREATE TABLE user_follows (
    user_follow_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    follower_user_id BIGINT NOT NULL REFERENCES app_users(user_id),
    followee_user_id BIGINT NOT NULL REFERENCES app_users(user_id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_user_follows_pair UNIQUE (follower_user_id, followee_user_id),
    CONSTRAINT ck_user_follows_not_self CHECK (follower_user_id <> followee_user_id)
);

CREATE INDEX ix_user_follows_follower ON user_follows (follower_user_id);
CREATE INDEX ix_user_follows_followee ON user_follows (followee_user_id);

CREATE TABLE recommendations (
    recommendation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(user_id),
    movie_slug VARCHAR(255) NOT NULL,
    score NUMERIC(6, 4) NOT NULL,
    reason VARCHAR(255),
    generated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_recommendations_movie_slug CHECK (length(trim(movie_slug)) > 0)
);

-- Không có UNIQUE(user_id, movie_slug): bảng ghi đè theo lô mỗi lần batch
-- job chạy (xóa hết dòng cũ của 1 User rồi chèn lại), không UPSERT từng
-- dòng, để giữ job đơn giản (ERD-R-18).
CREATE INDEX ix_recommendations_user_score ON recommendations (user_id, score DESC);

INSERT INTO roles (role_name, description)
VALUES
    ('USER', 'Người dùng xem phim'),
    ('ADMIN', 'Quản trị viên hệ thống')
ON CONFLICT (role_name) DO NOTHING;

COMMIT;
